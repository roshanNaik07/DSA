package com.examples.array;

class TwoDimentionalArrayDemo {

    public static void main(String[] args) {

        String[][] anArray = {
                {"Roshan", "Rishi", "Ketan"},
                {"Sarthak", "Manoj"},
        };

        System.out.println(anArray[0][0] + " " + anArray[0][2]);

        System.out.println(anArray[1][0] + " " + anArray[1][1]);

    }

}